def to_int(s: str):
    """عدد فارسی/عربی → int؛ نامعتبر → None."""
    s = (s or "").translate(
        str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩",
                      "01234567890123456789")).replace("٬", "").replace(",", "").strip()
    return int(s) if s.isdigit() else None


