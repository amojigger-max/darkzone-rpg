"""📝 جنگ جهانی — همه‌ی متن‌های فارسی: تمیز، خط‌کشی‌شده، ساده."""
import html

K = "━" * 18
# 📚 کتابخانه‌ی تزئین — خط‌کشی‌های خوشگل متنوع
FULL = "✦ " + "━" * 20 + " ✦"
DASH = "╾" + "─" * 18 + "╼"


FA_MAP = str.maketrans("0123456789,.", "۰۱۲۳۴۵۶۷۸۹٬٫")


def fa(x) -> str:
    """عدد یا رشته → رقم‌های فارسی تمیز: 993599 → ۹۹۳٬۵۹۹"""
    s = f"{x:,}" if isinstance(x, int) else str(x)
    return s.translate(FA_MAP)


def money(cid: str, amount) -> str:
    """💰 مبلغ بر حسب پول رسمی کشور با نرخ زنده‌ی امروز — دقیق، بدون گرد کردن."""
    import countries
    from game import economy
    nm = countries.CURRENCIES.get(cid, ("دلار", 1.0))[0]
    rate = economy.fx(cid)
    val = int(float(amount) * rate)
    return f"{fa(val)} {nm}"


def esc(s) -> str:
    return html.escape(str("" if s is None else s))


def hdr(title: str, emoji: str = "🌍") -> str:
    """سربرگ استاندارد کتابخانه‌ای: ✦ خط‌کشی ✦"""
    return f"{emoji} <b>{esc(title)}</b>\n{FULL}"


def row(label: str, value) -> str:
    """سطر مشخصات: برچسب — مقدار (اعداد خودکار فارسی)."""
    return f"▫️ {label}: <b>{esc(fa(value))}</b>"


def mention(uid: int, name: str) -> str:
    return f'<a href="tg://user?id={uid}">{esc(name)}</a>'


