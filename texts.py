def to_int(s: str):
    if not isinstance(s, str):
        return None
    s = s.translate(str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩", "01234567890123456789"))
    s = s.replace("٬", "").replace(",", "").strip()
    if not s or len(s)>16 or not s.isascii() or not s.isdigit():
        return None
    return int(s)


